function setLanguage(language) {
    const selectedLanguage = translations[language] ? language : "tr";
    const dictionary = translations[selectedLanguage];

    document.documentElement.lang = selectedLanguage;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const translation = dictionary[element.dataset.i18n];
        if (translation !== undefined) element.textContent = translation;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        const translation = dictionary[element.dataset.i18nAria];
        if (translation !== undefined) element.setAttribute("aria-label", translation);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
        const translation = dictionary[element.dataset.i18nTitle];
        if (translation !== undefined) element.title = translation;
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
        const isSelected = button.dataset.language === selectedLanguage;
        button.setAttribute("aria-pressed", String(isSelected));
    });

    document.title = dictionary["page.title"];
    try {
        localStorage.setItem("tatil-heyecani-language", selectedLanguage);
    } catch (error) {
        // Tarayıcı kaydetmeye izin vermiyorsa (ör. gizli mod) dil yine de değişir.
    }
}

function getSavedLanguage() {
    try {
        return localStorage.getItem("tatil-heyecani-language");
    } catch (error) {
        return null;
    }
}

document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
});

setLanguage(getSavedLanguage() || "tr");
